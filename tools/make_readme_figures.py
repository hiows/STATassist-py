def association(fig_dir: Path, notes: Notes) -> None:
    """Section 14: how two features move together, and the plot that reads it."""
    print("feature-pair association")
    n_feats = N_SHOWN
    cor_mat = sa.make_block_cor(
        n_features=n_feats,
        blocks=[
            {"features": range(0, 3), "cor": COR_TIGHT},
            {"features": range(3, 5), "cor": COR_MODERATE, "against": range(5, 7)},
        ],
    )
    sim = sa.simulate_regression(n_pred=n_feats, n_factor_pred=0, cor_mat=cor_mat, seed=SEED)
    feats = list(sim.args["predictors"])
    assoc = sa.summarize_association_stats(data=sim.args["data"], feats=feats)
    notes.add("s14 assoc['design']", assoc["design"])
    notes.add("s14 pearson corr, first block", assoc["pearson"]["corr"].iloc[:3, :3])

    figure(7.0, 6.0)
    sa.draw_corrplot(assoc["pearson"]["corr"])
    save(fig_dir, "corrplot")

    figure(7.0, 6.0)
    sa.draw_corrplot(assoc["pearson"]["corr"], pvalue=assoc["pearson"]["adj_pvalue"])
    save(fig_dir, "corrplot-masked")


def _model_cor() -> Any:
    """The correlation the modelling predictors are drawn with.

    The blocks straddle the planted predictors on purpose, so that one null
    predictor is drawn correlated with a planted one. A null that correlates
    with a signal is pulled off zero by the data alone, and no number of rows
    fixes it - every section of Part 2 runs into it, so it has to be in the
    data rather than described in prose.

    R's README offsets these blocks by one, and on its own random stream that
    lands the same way. It does not here: the same offset puts both planted
    predictors inside the 0.8 block, which leaves no correlated null at all.
    """
    return sa.make_block_cor(
        n_features=8,
        blocks=[
            {"features": range(1, 3), "cor": COR_STRONG},
            {"features": range(4, 7), "cor": COR_MODERATE},
        ],
    )


def _split(data: pd.DataFrame, stratified: Any, notes: Notes, tag: str) -> tuple[Any, Any, Any]:
    dataset = sa.split_data(data=data, stratified=stratified, p_train=0.75, times=1, seed=SEED)
    notes.show(tag, dataset)
    only = next(iter(dataset.datasets))
    return dataset, dataset.datasets[only]["train_data"], dataset.datasets[only]["test_data"]


def modelling(fig_dir: Path, notes: Notes) -> None:
    """Sections 15-25: known coefficients, a clean split, and models scored on it."""
    print("modelling")
    cor_mat = _model_cor()

    # Section 15 - regression data whose coefficients are known.
    sim_reg = sa.simulate_regression(cor_mat=cor_mat, noise_sd=NOISE_SD, seed=SEED)
    # The whole table rather than the planted rows alone: `max_cor_signal` is
    # only interesting on a null, where it says how far the data alone can pull
    # that predictor off the zero it was given.
    notes.add("s15 sim_reg.truth", sim_reg.truth)
    outcome = sim_reg.args["outcome"]
    predictors = list(sim_reg.args["predictors"])
    reg_data = sim_reg.args["data"]
    # Stratify on the one predictor that is not numeric, so both halves keep its
    # level balance rather than the split being told a column name.
    factor_cols = [c for c in predictors if not pd.api.types.is_numeric_dtype(reg_data[c])]
    _, train_data, test_data = _split(
        reg_data, reg_data[factor_cols[0]] if factor_cols else None, notes, "s15 dataset"
    )

    # Section 16 - linear regression.
    lin = sa.fit_linear_regression(
        data=train_data, outcome=outcome, predictors=predictors, **CV_ARGS
    )
    notes.show("s16 lin", lin)
    notes.add("s16 lin.coef()", lin.coef()[["terms", "estimate", "pval"]])

    # Section 17 - the same call with a two-class outcome.
    sim_cls = sa.simulate_classification(cor_mat=cor_mat, seed=SEED)
    cls_outcome = sim_cls.args["outcome"]
    cls_predictors = list(sim_cls.args["predictors"])
    outcome_lv = sim_cls.args.get("outcome_lv")
    cls_data = sim_cls.args["data"]
    _, cls_train, cls_test = _split(cls_data, cls_data[cls_outcome], notes, "s17 cls dataset")

    log_fit = sa.fit_logistic_regression(
        data=cls_train,
        outcome=cls_outcome,
        predictors=cls_predictors,
        outcome_lv=outcome_lv,
        **CV_ARGS,
    )
    notes.show("s17 log_fit", log_fit)
    notes.add("s17 log_fit.coef()", log_fit.coef()[["terms", "odds_ratio", "pval"]])

    # Section 18 - recursive feature elimination, inside the resampling. The
    # resampling is left at its default here: there is no `cv` argument to turn
    # off, because an elimination with nothing held out has no score to choose a
    # subset size by.
    rfe = sa.perform_rfe(
        data=cls_train,
        outcome=cls_outcome,
        predictors=cls_predictors,
        outcome_lv=outcome_lv,
        model="logistic",
        seed=SEED,
    )
    notes.show("s18 rfe", rfe)
    notes.add("s18 rfe.profile", rfe.profile)
    notes.add("s18 rfe.selected", rfe.selected)
    notes.add(
        "s18 planted predictors",
        list(sim_cls.truth.loc[sim_cls.truth["role"] != "null", "predictors"]),
    )

    # Section 19 - stepwise, which holds nothing out and charges per parameter.
    step = sa.perform_stepwise(
        data=cls_train,
        outcome=cls_outcome,
        predictors=cls_predictors,
        outcome_lv=outcome_lv,
        model="logistic",
        criterion="AIC",
    )
    notes.show("s19 step", step)
    notes.add("s19 step.profile", step.profile)
    notes.add("s19 step.selected", step.selected)
    bic = sa.perform_stepwise(
        data=cls_train,
        outcome=cls_outcome,
        predictors=cls_predictors,
        outcome_lv=outcome_lv,
        model="logistic",
        criterion="BIC",
    )
    notes.add("s19 step.selected under BIC", bic.selected)

    # Sections 20-22 in one place: the three engines with no coefficient table,
    # fitted on the predictors the search kept so section 23 compares engines
    # rather than column sets.
    eval_rfe = sa.perform_rfe(data=train_data, outcome=outcome, predictors=predictors, seed=SEED)
    kept = list(eval_rfe.selected)
    notes.add("s23 rfe.selected on the regression half", kept)

    fitted = {
        "linear": sa.fit_linear_regression(
            data=train_data, outcome=outcome, predictors=kept, **CV_ARGS
        ),
        "lasso": sa.fit_elastic_net(
            data=train_data,
            outcome=outcome,
            predictors=kept,
            penalty="lasso",
            lambda_=LAMBDA_GRID,
            **CV_ARGS,
        ),
        "rf": sa.fit_rf(data=train_data, outcome=outcome, predictors=kept, **CV_ARGS),
        "svm": sa.fit_svm(data=train_data, outcome=outcome, predictors=kept, **CV_ARGS),
    }
    notes.add("s20 lasso coef()", fitted["lasso"].coef())
    notes.add("s21 rf coef()", fitted["rf"].coef())
    notes.add("s22 svm coef() columns", list(fitted["svm"].coef().columns))

    baseline_label = "linear"
    baseline = fitted[baseline_label]
    eval_reg = sa.evaluate_regression_models(
        baseline_model=baseline,
        new_models={k: v for k, v in fitted.items() if k != baseline_label},
        newdata=test_data,
        answer=test_data[outcome],
        baseline_label=baseline_label,
    )
    notes.show("s23 eval_reg", eval_reg)
    notes.add("s23 eval_reg.metrics", eval_reg.metrics)
    notes.add("s23 eval_reg.comparisons", eval_reg.comparisons)

    figure(7.5, 6.0)
    sa.draw_prediction_plot(eval_reg, type="overlay", anno_corr=True, anno_rsq=True)
    save(fig_dir, "eval-regression")

    # Section 24 - the same shape for a two-class outcome.
    kept_cls = list(rfe.selected)
    fitted_cls = {
        "logistic": sa.fit_logistic_regression(
            data=cls_train,
            outcome=cls_outcome,
            predictors=kept_cls,
            outcome_lv=outcome_lv,
            **CV_ARGS,
        ),
        "lasso": sa.fit_elastic_net(
            data=cls_train,
            outcome=cls_outcome,
            predictors=kept_cls,
            outcome_lv=outcome_lv,
            penalty="lasso",
            lambda_=LAMBDA_GRID,
            **CV_ARGS,
        ),
        "rf": sa.fit_rf(
            data=cls_train,
            outcome=cls_outcome,
            predictors=kept_cls,
            outcome_lv=outcome_lv,
            **CV_ARGS,
        ),
        "svm": sa.fit_svm(
            data=cls_train,
            outcome=cls_outcome,
            predictors=kept_cls,
            outcome_lv=outcome_lv,
            **CV_ARGS,
        ),
    }
    cls_baseline_label = "logistic"
    eval_cls = sa.evaluate_classification_models(
        baseline_model=fitted_cls[cls_baseline_label],
        new_models={k: v for k, v in fitted_cls.items() if k != cls_baseline_label},
        newdata=cls_test,
        answer=cls_test[cls_outcome],
        outcome_lv=outcome_lv,
        baseline_label=cls_baseline_label,
    )
    notes.show("s24 eval_cls", eval_cls)
    notes.add("s24 eval_cls.metrics", eval_cls.metrics)
    notes.add("s24 eval_cls.comparisons", eval_cls.comparisons)

    figure(7.0, 6.0)
    sa.draw_roc_curve(eval_cls, anno_auc=True)
    save(fig_dir, "eval-classification")

    # Section 25 - the prediction interface itself.
    notes.add("s25 predict, numeric", baseline.predict(newdata=test_data)[:5])
    logistic = fitted_cls[cls_baseline_label]
    notes.add("s25 predict, type='raw'", logistic.predict(newdata=cls_test, type="raw")[:5])
    notes.add(
        "s25 predict, type='prob'",
        logistic.predict(newdata=cls_test, type="prob").head(),
    )
    notes.add(
        "s25 predict, type='response'",
        logistic.predict(newdata=cls_test, type="response")[:5],
    )


def unsupervised(fig_dir: Path, notes: Notes) -> None:
    """Sections 26-27: fewer coordinates, then labels on top of them."""
    print("dimension reduction and clustering")
    n_feats = 8
    red_cor = sa.make_block_cor(
        n_features=n_feats,
        blocks=[
            {"features": range(0, 2), "cor": COR_STRONG},
            {"features": range(2, 5), "cor": COR_MODERATE},
            {"features": range(6, 8), "cor": COR_TIGHT},
        ],
    )
    sim = sa.simulate_classification(cor_mat=red_cor, seed=SEED)
    numeric = [
        c for c in sim.args["predictors"] if pd.api.types.is_numeric_dtype(sim.args["data"][c])
    ]
    red_data = sim.args["data"]

    pca = sa.perform_pca(
        data=red_data, feats=numeric, embedding_scale="features", center=True, scale=True
    )
    notes.show("s26 pca", pca)
    notes.add("s26 pca.scores", pca.scores.iloc[:, :3])
    notes.add("s26 pca.variance", pca.variance.head())

    figure(6.5, 6.0)
    sa.draw_dim_reduction_plot(pca, anno_points=True)
    save(fig_dir, "pca")

    # Eight points is a small neighbourhood, so perplexity has to come down with
    # it rather than keeping the engine default.
    perplexity = max(1.0, (len(numeric) - 1) / 3)
    tsne = sa.perform_tsne(
        data=red_data,
        feats=numeric,
        embedding_scale="features",
        center=True,
        scale=True,
        perplexity=perplexity,
        seed=SEED,
    )
    notes.show("s26 tsne", tsne)
    figure(6.5, 6.0)
    sa.draw_dim_reduction_plot(tsne, anno_points=True)
    save(fig_dir, "tsne")

    try:
        umap_res = sa.perform_umap(
            data=red_data,
            feats=numeric,
            embedding_scale="features",
            n_neighbors=3,
            seed=SEED,
        )
    except Exception as exc:  # noqa: BLE001 - the extra is optional by design
        notes.add("s26 umap", f"skipped: {exc}")
        print("  skipped UMAP (install the `umap` extra to include it)")
    else:
        notes.show("s26 umap", umap_res)
        figure(6.5, 6.0)
        sa.draw_dim_reduction_plot(umap_res, anno_points=True)
        save(fig_dir, "umap")

    # Section 27 - a clustering read against a grouping that was known already.
    clust_sim = sa.simulate_two_groups(n_feats=50, deg_log2fc=(5, 10), seed=SEED)
    clust_pca = sa.perform_pca(
        data=clust_sim.args["data"],
        feats=clust_sim.args["feats"],
        embedding_scale="samples",
    )
    n_clust = len(clust_sim.args["group_lv"])
    clust_km = sa.cluster_kmeans(
        data=clust_pca.scores,
        feats=list(clust_pca.scores.columns[1 : 1 + 2]),
        cluster_scale="samples",
        n_clust=n_clust,
        seed=SEED,
    )
    notes.show("s27 clust_km", clust_km)
    notes.add(
        "s27 planted group vs cluster",
        pd.crosstab(
            pd.Series(clust_sim.args["group"], name="group"),
            pd.Series(clust_km.assignments["cluster"].to_numpy(), name="cluster"),
        ),
    )

    figure(6.5, 6.0)
    sa.draw_dim_reduction_plot(
        clust_pca, group=clust_sim.args["group"], group_lv=clust_sim.args["group_lv"]
    )
    save(fig_dir, "cluster-pca-group")

    figure(6.5, 6.0)
    sa.draw_dim_reduction_plot(clust_pca, cluster_result=clust_km)
    save(fig_dir, "cluster-pca-cluster")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fig-dir", type=Path, default=DEFAULT_FIG_DIR)
    parser.add_argument("--text-out", type=Path, default=DEFAULT_TEXT_OUT)
    parser.add_argument(
        "--only",
        nargs="*",
        default=None,
        help="run a subset of the sections, by function name",
    )
    args = parser.parse_args(argv)

    # Wide enough that the tables the README quotes print on one line each. A
    # wrapped frame is still correct, but it cannot be pasted into a document
    # and read as the table it is.
    pd.set_option("display.width", 120)
    pd.set_option("display.max_columns", None)

    sections = {
        "two_groups": two_groups,
        "multiple_groups": multiple_groups,
        "factorial_groups": factorial_groups,
        "categorical_groups": categorical_groups,
        "association": association,
        "modelling": modelling,
        "unsupervised": unsupervised,
    }
    chosen = args.only or list(sections)
    unknown = [name for name in chosen if name not in sections]
    if unknown:
        parser.error(f"unknown section(s): {', '.join(unknown)}")

    notes = Notes()
    for name in chosen:
        sections[name](args.fig_dir, notes)
    notes.write(args.text_out)
    print(f"wrote {_shown(args.text_out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
