"""Regenerate every figure and printed output the top-level README shows.

The README is a workflow document: each section runs on data whose answer was
planted, so the verdict it reports can be scored rather than trusted. Nothing in
it may be transcribed from the R package or edited by hand, which is what this
script is for - it runs the README end to end, writes the figures next to it and
dumps every table and repr the prose quotes into one text file.

Run it from the repository root::

    python tools/make_readme_figures.py

``perform_umap()`` needs the ``umap`` extra. When it is not installed the UMAP
section is skipped and says so, the same way the docstring example does, so the
rest of the figures still regenerate on a plain install.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

import statassist as sa  # noqa: E402

# One seed for every simulation in the README, so a reader who copies a block
# gets the numbers the prose quotes.
SEED = 2026

# The figures are read on GitHub and on PyPI rather than zoomed into, so they are
# sized for a README column rather than for print.
DPI = 130

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_FIG_DIR = REPO_ROOT / "docs" / "figures"
DEFAULT_TEXT_OUT = REPO_ROOT / "docs" / "readme_outputs.txt"

# The two-group example is the one the top of the README opens with: thirty
# features, sixteen of them moved, so the verdict has both kinds of mistake
# available to it.
N_FEATS_TWO = 30
N_MOVED_EACH_WAY = 8

# How many features the plots that draw one panel per feature are given.
N_SHOWN = 10

# The cutoffs the README thresholds on. They are the defaults of
# `estimate_significance()`, named here because the prose quotes them.
LOG2FC_CUTOFF = 1.0
PVAL_CUTOFF = 0.05

# The correlation planted between predictors, so a null predictor that
# correlates with a planted one can be pointed at by name later.
COR_STRONG = 0.8
COR_MODERATE = 0.5
COR_TIGHT = 0.9

# Below the simulator's own default of 3. Part 2 is read for what the tables and
# the prediction plot look like when a model has something to find, and at the
# default the residual swamps the planted coefficients on 200 rows.
NOISE_SD = 2

CV_ARGS: dict[str, Any] = {
    "cv": True,
    "cv_method": "repeated_kfold",
    "n_fold": 10,
    "n_repeat": 3,
    "seed": SEED,
}

# A penalty grid wide enough that the resampling has something to choose between.
# Left to itself the engine can settle on a lambda small enough that the fit is
# the unpenalized one, which says nothing about what a penalty does.
LAMBDA_GRID = (0.01, 0.1, 0.5, 1.0, 2.0)


class Notes:
    """Everything the README prose quotes, in the order the README quotes it."""

    def __init__(self) -> None:
        self._blocks: list[tuple[str, str]] = []

    def add(self, tag: str, value: Any) -> None:
        text = value if isinstance(value, str) else repr(value)
        self._blocks.append((tag, text.rstrip()))
        print(f"  recorded {tag}")

    def show(self, tag: str, value: Any) -> None:
        """Record the ``str()`` of a result, which is what a reader would see."""
        self.add(tag, str(value))

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        rule = "=" * 79
        parts = [
            "Generated by tools/make_readme_figures.py.",
            "Every block below is quoted verbatim by README.md - edit the script,",
            "rerun it and paste, rather than editing either file by hand.",
            "",
        ]
        for tag, text in self._blocks:
            parts.extend([rule, tag, rule, "", text, ""])
        path.write_text("\n".join(parts), encoding="utf-8")


def _shown(path: Path) -> str:
    """The path as the reader would type it, when it sits inside the repository."""
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def save(fig_dir: Path, name: str) -> None:
    """Write the current figure out under the README's naming convention."""
    fig_dir.mkdir(parents=True, exist_ok=True)
    path = fig_dir / f"README-{name}.png"
    plt.gcf().savefig(path, dpi=DPI, bbox_inches="tight")
    plt.close("all")
    print(f"  wrote {_shown(path)}")


def figure(width: float, height: float) -> None:
    plt.close("all")
    plt.figure(figsize=(width, height))


def two_groups(fig_dir: Path, notes: Notes) -> None:
    """Sections 1-6: the comparison, its verdict, and the plots that read them."""
    print("two-group comparison")
    sim = sa.simulate_two_groups(
        n_feats=N_FEATS_TWO,
        n_up=N_MOVED_EACH_WAY,
        n_down=N_MOVED_EACH_WAY,
        seed=SEED,
    )
    comp_res = sa.compare_two_groups(**sim.args)
    notes.show("s01 comp_res", comp_res)
    notes.add("s01 comp_res.effect.head(4)", comp_res.effect.head(4))

    sig = sa.estimate_significance(
        comp_res,
        test="t_test",
        log2fc_cutoff=LOG2FC_CUTOFF,
        pval_cutoff=PVAL_CUTOFF,
        adj_type="BH",
    )
    notes.show("s02 sig", sig)
    verdict = sig.significance

    figure(7.0, 6.0)
    sa.draw_volcano_plot(sig)
    save(fig_dir, "volcano")

    # Section 3 - score the verdict against the answer that was planted.
    planted = sim.truth["direction"].to_numpy() != "none"
    called = verdict["is_signif"].fillna(False).to_numpy()
    notes.add(
        "s03 planted vs called",
        pd.crosstab(
            pd.Series(planted, name="planted"),
            pd.Series(called, name="called"),
        ),
    )

    recall = {
        name: float(
            sa.estimate_significance(comp_res, test=name)
            .significance["is_signif"]
            .fillna(False)
            .to_numpy()[planted]
            .mean()
        )
        for name in comp_res.tests
    }
    notes.add("s03 recall by test family", recall)

    missed = planted & ~called
    notes.add("s03 sim.truth[missed]", sim.truth[missed])
    notes.add("s03 verdict[missed]", verdict[missed])

    # Section 4 - the plots that read the data rather than a result.
    shown = list(sim.args["feats"])[:N_SHOWN]
    figure(9.0, 5.5)
    sa.draw_grouped_boxplot(
        data=sim.args["data"],
        feats=shown,
        group=sim.args["group"],
        group_lv=sim.args["group_lv"],
    )
    save(fig_dir, "boxplot")

    # Section 13, drawn here because it reads the same ten features from the same
    # simulation: the spread each group has, and then the one number standing for
    # it, so the two pictures can be read against each other.
    figure(9.0, 5.5)
    sa.draw_grouped_barplot(
        data=sim.args["data"],
        feats=shown,
        group=sim.args["group"],
        group_lv=sim.args["group_lv"],
        errorbar="se",
    )
    save(fig_dir, "barplot")

    # The feature the verdict is most certain about, so the two groups visibly
    # separate rather than being picked by name.
    strongest = str(verdict.sort_values("adj_pvalue")["features"].iloc[0])
    notes.add("s04 strongest feature", strongest)
    figure(7.5, 5.5)
    sa.draw_butterfly_hist(
        data=sim.args["data"],
        feat=strongest,
        group=sim.args["group"],
        group_lv=sim.args["group_lv"],
        type="both",
    )
    save(fig_dir, "butterfly")

    # Section 5 - one function, two views of the same table.
    figure(7.5, 6.0)
    sa.draw_forest_plot(comp_res, test="t_test", type="estimate", feats=shown, sort_by="pvalue")
    save(fig_dir, "forest-estimate")

    figure(7.5, 6.0)
    sa.draw_forest_plot(comp_res, test="t_test", type="pvalue", feats=shown, sort_by="pvalue")
    save(fig_dir, "forest-pvalue")

    # Section 6 - the heatmap, and the clustering it hands back.
    figure(9.0, 7.0)
    drawn = sa.draw_heatmap(
        data=sim.args["data"],
        group=sim.args["group"],
        group_lv=sim.args["group_lv"],
        scale="feature",
        hclust_method="ward.D2",
        show_sample_names=False,
    )
    save(fig_dir, "heatmap")
    notes.add("s06 drawn.keys()", sorted(drawn))
    notes.add("s06 drawn['matrix'].index", list(drawn["matrix"].index[:5]))
    # The plot was never told where the groups are. Whether it put them together
    # anyway is answered by the longest unbroken run of each along the columns.
    ordered = pd.Series(pd.Series(sim.args["group"]).to_numpy()[drawn["sample_order"]])
    runs = ordered.groupby((ordered != ordered.shift()).cumsum())
    longest = (
        pd.DataFrame({"group": [g.iloc[0] for _, g in runs], "run": [len(g) for _, g in runs]})
        .groupby("group")["run"]
        .max()
    )
    notes.add("s06 longest run per group along sample_order", longest)


def multiple_groups(fig_dir: Path, notes: Notes) -> None:
    """Section 7: an omnibus test and the post-hoc stage that shares its assumptions."""
    print("multi-group comparison")
    sim = sa.simulate_multiple_groups(
        n_feats=N_SHOWN,
        n_control=50,
        n_treat=(50, 50, 50),
        n_up=3,
        n_down=3,
        seed=SEED,
    )
    multi = sa.compare_multiple_groups(**sim.args)
    notes.show("s07 multi", multi)

    anova = multi.tests["anova_test"]
    notes.add(
        "s07 multi.tests['anova_test']",
        anova[["features", "n_used", "f_stat", "eta_sq", "pval_adj"]],
    )

    # The feature the omnibus test is most certain about, so the contrasts below
    # have something to separate.
    lead = str(anova.sort_values("pval_adj")["features"].iloc[0])
    notes.add("s07 leading feature", lead)
    posthoc = multi.posthoc["anova_test"]
    notes.add(
        "s07 posthoc for the leading feature",
        posthoc.loc[posthoc["features"] == lead, ["contrast", "estimate", "pval_adj"]],
    )
    notes.add("s07 pairwise contrast labels", list(multi.pairwise["anova_test"]))

    figure(7.5, 4.5)
    sa.draw_forest_plot(multi, test="anova_test", type="posthoc", feats=lead, sort_by="pvalue")
    save(fig_dir, "multi-posthoc")

    sig_multi = sa.estimate_significance(
        multi, test="anova_test", pval_cutoff=PVAL_CUTOFF, adj_type="BH"
    )
    notes.show("s07 sig_multi", sig_multi)
    figure(7.0, 6.0)
    sa.draw_volcano_plot(sig_multi)
    save(fig_dir, "multi-volcano")


def factorial_groups(fig_dir: Path, notes: Notes) -> None:
    """Section 8: two crossed factors, with the answer planted per model term."""
    print("factorial comparison")
    sim = sa.simulate_factorial_groups(seed=SEED)
    # Naming a reference level per factor fixes what `$effect` is measured against.
    # The simulators list the reference first, so this states the default rather
    # than changing it.
    control_label = {name: list(levels)[0] for name, levels in sim.args["factor_lv"].items()}
    notes.add("s08 control_label", control_label)

    fact = sa.compare_factorial_groups(**sim.args, control_label=control_label)
    notes.show("s08 fact", fact)
    notes.add("s08 fact.effect.head(3)", fact.effect.head(3))

    # A crossover: both main effects flat, the interaction moved. It is the one
    # shape a single-factor reading cannot see, so it is worth drawing.
    truth_term = sim.truth_term
    is_interaction = truth_term["term_order"] > 1

    def is_crossover(rows: pd.DataFrame) -> bool:
        return bool(
            rows.loc[is_interaction[rows.index], "is_effect"].any()
            and not rows.loc[~is_interaction[rows.index], "is_effect"].any()
        )

    # `sort=False` keeps the order the simulator generated the features in, so
    # this picks the first crossover rather than the first one alphabetically.
    crossovers = [
        name for name, rows in truth_term.groupby("features", sort=False) if is_crossover(rows)
    ]
    crossover = str(crossovers[0])
    notes.add("s08 crossover feature", crossover)
    notes.add(
        "s08 truth_term for the crossover",
        truth_term[truth_term["features"] == crossover],
    )
    notes.add(
        "s08 fact.terms for the crossover",
        fact.terms.loc[
            fact.terms["features"] == crossover,
            ["terms", "f_stat", "partial_eta_sq", "log2_effect", "pval_adj"],
        ],
    )

    sig_term = sa.estimate_significance(fact, by="term")
    notes.show("s08 sig_term", sig_term)
    figure(9.0, 4.5)
    sa.draw_volcano_plot(sig_term)
    save(fig_dir, "factorial-volcano")

    figure(7.0, 5.0)
    sa.draw_interaction_plot(fact, feats=crossover, errorbar="se")
    save(fig_dir, "factorial-interaction")


