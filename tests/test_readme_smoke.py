class TestPartOne:
    """Sections 1-9 and 14."""

    def test_the_simulator_arguments_go_straight_into_the_comparison(self, two_group):
        sim, comp_res = two_group
        assert set(sim.args) >= {"data", "feats", "group", "group_lv", "input_scale"}
        assert list(comp_res.effect.columns) == [
            "features",
            "x_center",
            "y_center",
            "fold_change",
            "log2fc",
        ]
        assert {"t_test", "wilcox_test", "robust_test"} <= set(comp_res.tests)

    def test_a_slot_is_reachable_as_an_attribute_and_as_a_key(self, two_group):
        _, comp_res = two_group
        assert comp_res.effect is comp_res["effect"]

    def test_the_verdict_can_be_scored_against_the_planted_answer(self, two_group):
        sim, comp_res = two_group
        sig = sa.estimate_significance(
            comp_res, test="t_test", log2fc_cutoff=1, pval_cutoff=0.05, adj_type="BH"
        )
        verdict = sig.significance
        assert list(verdict.columns) == [
            "features",
            "log2fc",
            "pvalue",
            "adj_pvalue",
            "is_signif",
        ]
        # Section 3 lines the two up by position, so they have to stay aligned.
        assert list(verdict["features"]) == list(sim.truth["features"])

    def test_the_plots_that_read_a_result_and_the_ones_that_read_the_data(self, two_group):
        sim, comp_res = two_group
        sig = sa.estimate_significance(comp_res, test="t_test")
        feats = list(sim.args["feats"])

        sa.draw_volcano_plot(sig)
        sa.draw_forest_plot(comp_res, test="t_test", type="estimate", feats=feats)
        sa.draw_forest_plot(comp_res, test="t_test", type="pvalue", feats=feats)
        sa.draw_grouped_boxplot(
            data=sim.args["data"],
            feats=feats,
            group=sim.args["group"],
            group_lv=sim.args["group_lv"],
        )
        sa.draw_butterfly_hist(
            data=sim.args["data"],
            feat=feats[0],
            group=sim.args["group"],
            group_lv=sim.args["group_lv"],
            type="both",
        )

    def test_the_heatmap_hands_back_the_clustering_the_readme_reads(self, two_group):
        sim, _ = two_group
        drawn = sa.draw_heatmap(
            data=sim.args["data"],
            group=sim.args["group"],
            group_lv=sim.args["group_lv"],
            scale="feature",
            hclust_method="ward.D2",
            show_sample_names=False,
        )
        assert {"matrix", "sample_order", "feat_order", "sample_hclust", "feat_hclust"} <= set(
            drawn
        )
        assert len(drawn["sample_order"]) == len(sim.args["group"])

    def test_the_omnibus_test_carries_a_post_hoc_stage_and_pairwise_tables(self):
        # The effect is planted wide of the default range so that a post-hoc
        # stage certainly runs: it only runs for features whose omnibus test
        # qualified, and there is nothing to draw when none of them did.
        sim = sa.simulate_multiple_groups(
            n_feats=4,
            n_control=20,
            n_treat=(20, 20),
            n_up=1,
            n_down=1,
            deg_log2fc=(5, 10),
            seed=SEED,
        )
        multi = sa.compare_multiple_groups(**sim.args)
        assert "posthoc" in multi and "pairwise" in multi
        assert set(multi.posthoc) == set(multi.tests)

        lead = multi.tests["anova_test"].sort_values("pval_adj")["features"].iloc[0]
        sa.draw_forest_plot(multi, test="anova_test", type="posthoc", feats=lead)
        sa.draw_volcano_plot(sa.estimate_significance(multi, test="anova_test"))

    def test_a_crossed_design_answers_per_term_and_draws_an_interaction(self):
        sim = sa.simulate_factorial_groups(n_feats=6, seed=SEED)
        control_label = {name: list(lv)[0] for name, lv in sim.args["factor_lv"].items()}
        fact = sa.compare_factorial_groups(**sim.args, control_label=control_label)
        assert "terms" in fact and "cells" in fact

        sig_term = sa.estimate_significance(fact, by="term")
        assert isinstance(sig_term.significance, dict)
        sa.draw_volcano_plot(sig_term)
        sa.draw_interaction_plot(fact, feats=fact.features[0], errorbar="se")

    def test_a_contingency_table_refuses_the_wrong_significance_function(self):
        sim = sa.simulate_categorical_groups(seed=SEED)
        cat = sa.compare_categorical_groups(**sim.args)
        assert {"chisq_test", "fisher_test"} <= set(cat.tests)
        assert isinstance(cat.as_table(), pd.DataFrame)

        with pytest.raises(Exception, match="must be a comparison result"):
            sa.estimate_significance(cat)

        by_cell = sa.estimate_categorical_significance(cat, by="cell")
        assert {"row_level", "col_level", "lift", "is_signif"} <= set(by_cell.significance.columns)
        sa.estimate_categorical_significance(cat, by="table", test="chisq_test")
        sa.draw_mosaic_plot(cat)

    def test_association_returns_one_square_matrix_set_per_method(self):
        cor_mat = sa.make_block_cor(
            n_features=6,
            blocks=[
                {"features": range(0, 3), "cor": 0.9},
                {"features": range(3, 5), "cor": 0.5, "against": range(5, 6)},
            ],
        )
        sim = sa.simulate_regression(n_pred=6, n_factor_pred=0, cor_mat=cor_mat, seed=SEED)
        feats = list(sim.args["predictors"])
        assoc = sa.summarize_association_stats(data=sim.args["data"], feats=feats)

        for method in assoc["design"]["methods"]:
            assert assoc[method]["corr"].shape == (len(feats), len(feats))
        sa.draw_corrplot(assoc["pearson"]["corr"])
        sa.draw_corrplot(assoc["pearson"]["corr"], pvalue=assoc["pearson"]["adj_pvalue"])


