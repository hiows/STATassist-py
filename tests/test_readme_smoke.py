"""The README as a test: every path it walks still runs, and its figures exist.

The README is one long worked example, and the way it rots is silent — a keyword
renamed, a slot moved, a figure deleted, and the document still reads fine while
nothing in it runs. What is checked here is the calling contract rather than the
numbers: that the arguments the README passes are still accepted, that the slots
it reads are still there, and that the columns it prints are still named what it
says. The numbers themselves are regenerated by ``tools/make_readme_figures.py``
and graded against R by the rest of this suite.

Sizes are cut down from the README's, since none of these assertions is about
how many features there were. ``seed=SEED`` is kept because a smoke test that
fails one run in ten is worse than none.
"""

from __future__ import annotations

import re
from pathlib import Path

import matplotlib
import pandas as pd
import pytest

matplotlib.use("Agg")

import statassist as sa  # noqa: E402

#: The README's seed, so a failure here can be reproduced by running the README.
SEED = 2026
# Matches tools/make_readme_figures.py, which is what the README's numbers came from.
NOISE_SD = 2

REPO_ROOT = Path(__file__).resolve().parent.parent
README = REPO_ROOT / "README.md"
FIG_DIR = REPO_ROOT / "docs" / "figures"

#: Images have to resolve for a reader who is on neither GitHub nor a checkout,
#: which is what PyPI is, and PyPI does not resolve a relative path.
RAW_URL_PREFIX = "https://raw.githubusercontent.com/hiows/STATassist-py/master/docs/figures/"

_MARKDOWN_IMAGE = re.compile(r"!\[[^\]]*\]\(([^)]+)\)")


@pytest.fixture(autouse=True)
def _clean_figure():
    import matplotlib.pyplot as plt

    plt.close("all")
    yield
    plt.close("all")


class TestFigures:
    """The images the README points at, against the ones on disk."""

    def test_every_image_is_an_absolute_raw_url_so_pypi_can_render_it(self):
        referenced = _MARKDOWN_IMAGE.findall(README.read_text(encoding="utf-8"))
        assert referenced, "the README stopped showing any figure at all"
        for url in referenced:
            assert url.startswith(RAW_URL_PREFIX), url

    def test_every_referenced_figure_is_committed(self):
        referenced = _MARKDOWN_IMAGE.findall(README.read_text(encoding="utf-8"))
        for url in referenced:
            assert (FIG_DIR / url.removeprefix(RAW_URL_PREFIX)).is_file(), url

    def test_no_figure_is_carried_without_being_shown(self):
        """A figure nobody references is one the generator no longer produces."""
        text = README.read_text(encoding="utf-8")
        for path in FIG_DIR.glob("*.png"):
            assert path.name in text, path.name


