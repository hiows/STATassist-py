class TestPartTwo:
    """Sections 15-25."""

    def test_the_split_reports_what_it_actually_reached(self, regression):
        _, split, train_data, test_data = regression
        assert len(train_data.index) + len(test_data.index) == len(split.full_data.index)
        assert "achieved_p" in split.parameters

    def test_the_truth_table_names_the_nulls_that_correlate_with_a_signal(self, regression):
        sim, *_ = regression
        truth = sim.truth
        assert {"role", "beta", "max_cor_signal"} <= set(truth.columns)
        # Section 15 turns on there being one, which the correlation blocks plant.
        pulled = truth[(truth["role"] == "null") & (truth["max_cor_signal"] > 0)]
        assert not pulled.empty

    def test_a_fitted_model_answers_coef_and_predict_whatever_engine_it_used(
        self, regression, classification
    ):
        sim_reg, _, train_data, test_data = regression
        outcome = sim_reg.args["outcome"]
        predictors = list(sim_reg.args["predictors"])

        lin = sa.fit_linear_regression(
            data=train_data, outcome=outcome, predictors=predictors, cv=False
        )
        assert {"terms", "estimate", "pval"} <= set(lin.coef().columns)
        assert len(lin.predict(newdata=test_data)) == len(test_data.index)
        # `fit` is a handle, not a slot: it must not travel in the JSON-able form.
        assert lin.fit is not None
        assert "fit" not in lin.to_dict()

        sim_cls, cls_train, cls_test = classification
        log_fit = sa.fit_logistic_regression(
            data=cls_train,
            outcome=sim_cls.args["outcome"],
            predictors=list(sim_cls.args["predictors"]),
            outcome_lv=sim_cls.args["outcome_lv"],
            cv=False,
        )
        assert {"odds_ratio", "or_lower_conf", "or_upper_conf"} <= set(log_fit.coef().columns)
        assert set(log_fit.predict(newdata=cls_test, type="prob").columns) == set(
            sim_cls.args["outcome_lv"]
        )
        assert len(log_fit.predict(newdata=cls_test, type="response")) == len(cls_test.index)
        assert set(log_fit.predict(newdata=cls_test, type="raw")) <= set(sim_cls.args["outcome_lv"])

    def test_a_penalized_fit_omits_the_inference_it_cannot_honestly_give(self, regression):
        _, _, train_data, _ = regression
        sim_reg, *_ = regression
        lasso = sa.fit_elastic_net(
            data=train_data,
            outcome=sim_reg.args["outcome"],
            predictors=list(sim_reg.args["predictors"]),
            penalty="lasso",
            lambda_=(0.01, 0.1, 0.5, 1.0, 2.0),
            cv=True,
            seed=SEED,
        )
        columns = set(lasso.coef().columns)
        assert "selected" in columns
        assert not columns & {"stderr", "pval", "lower_conf", "upper_conf"}

    def test_both_searches_return_the_same_contract_on_a_candidates_axis(self, classification):
        sim_cls, cls_train, _ = classification
        shared = {
            "data": cls_train,
            "outcome": sim_cls.args["outcome"],
            "predictors": list(sim_cls.args["predictors"]),
            "outcome_lv": sim_cls.args["outcome_lv"],
            "model": "logistic",
        }
        rfe = sa.perform_rfe(**shared, seed=SEED)
        step = sa.perform_stepwise(**shared, criterion="AIC")

        for search in (rfe, step):
            assert list(search.ranking["candidates"]) != []
            assert set(search.selected) <= set(search.candidates)
            assert "n_vars" in search.profile.columns
            assert bool(search.profile["chosen"].any())
        # Section 19 leans on this: nothing was held out, so nothing was resampled.
        assert step.resampling is None

    def test_models_are_scored_on_the_same_held_out_rows(self, regression, classification):
        sim_reg, _, train_data, test_data = regression
        outcome = sim_reg.args["outcome"]
        kept = list(
            sa.perform_rfe(
                data=train_data,
                outcome=outcome,
                predictors=list(sim_reg.args["predictors"]),
                seed=SEED,
            ).selected
        )

        eval_reg = sa.evaluate_regression_models(
            baseline_model=sa.fit_linear_regression(
                data=train_data, outcome=outcome, predictors=kept, cv=False
            ),
            new_models={
                "rf": sa.fit_rf(
                    data=train_data, outcome=outcome, predictors=kept, cv=False, seed=SEED
                )
            },
            newdata=test_data,
            answer=test_data[outcome],
            baseline_label="linear",
        )
        assert "curves" not in eval_reg
        assert {"model", "cor", "r_squared", "rmse", "calib_slope"} <= set(eval_reg.metrics.columns)
        assert set(eval_reg.metrics["n_used"]) == {len(test_data.index)}
        sa.draw_prediction_plot(eval_reg, type="overlay", anno_corr=True, anno_rsq=True)

        sim_cls, cls_train, cls_test = classification
        cls_outcome = sim_cls.args["outcome"]
        outcome_lv = sim_cls.args["outcome_lv"]
        cls_kept = list(sim_cls.truth.loc[sim_cls.truth["role"] != "null", "predictors"])
        shared = {
            "data": cls_train,
            "outcome": cls_outcome,
            "predictors": cls_kept,
            "outcome_lv": outcome_lv,
            "cv": False,
        }
        eval_cls = sa.evaluate_classification_models(
            baseline_model=sa.fit_logistic_regression(**shared),
            new_models={"rf": sa.fit_rf(**shared, seed=SEED)},
            newdata=cls_test,
            answer=cls_test[cls_outcome],
            outcome_lv=outcome_lv,
            baseline_label="logistic",
        )
        assert "curves" in eval_cls
        assert {"auc", "brier", "accuracy"} <= set(eval_cls.metrics.columns)
        assert {"delta_auc", "idi", "nri"} <= set(eval_cls.comparisons.columns)
        sa.draw_roc_curve(eval_cls, anno_auc=True)


