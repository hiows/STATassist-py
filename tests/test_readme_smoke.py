class TestPartThree:
    """Sections 26-27."""

    def test_a_rotation_carries_variance_and_an_embedding_does_not(self, reduction_data):
        data, feats = reduction_data
        pca = sa.perform_pca(
            data=data, feats=feats, embedding_scale="features", center=True, scale=True
        )
        assert "variance" in pca and "loadings" in pca
        assert list(pca.scores["points"]) == feats
        sa.draw_dim_reduction_plot(pca, anno_points=True)

        tsne = sa.perform_tsne(
            data=data,
            feats=feats,
            embedding_scale="features",
            center=True,
            scale=True,
            perplexity=(len(feats) - 1) / 3,
            seed=SEED,
        )
        assert "variance" not in tsne
        sa.draw_dim_reduction_plot(tsne, anno_points=True)

    def test_umap_answers_on_the_same_points_when_the_extra_is_installed(self, reduction_data):
        pytest.importorskip("umap", reason="`perform_umap()` needs the optional `umap` extra")
        data, feats = reduction_data
        umap_res = sa.perform_umap(
            data=data, feats=feats, embedding_scale="features", n_neighbors=3, seed=SEED
        )
        assert list(umap_res.scores["points"]) == feats
        sa.draw_dim_reduction_plot(umap_res, anno_points=True)

    def test_a_clustering_lands_on_the_same_points_the_embedding_did(self):
        sim = sa.simulate_two_groups(n_feats=20, n_up=5, n_down=5, deg_log2fc=(5, 10), seed=SEED)
        pca = sa.perform_pca(
            data=sim.args["data"], feats=sim.args["feats"], embedding_scale="samples"
        )
        clust = sa.cluster_kmeans(
            data=pca.scores,
            feats=["PC1", "PC2"],
            cluster_scale="samples",
            n_clust=len(sim.args["group_lv"]),
            seed=SEED,
        )
        assert {"points", "cluster", "silhouette"} <= set(clust.assignments.columns)
        assert list(clust.points) == list(pca.points)

        sa.draw_dim_reduction_plot(pca, group=sim.args["group"], group_lv=sim.args["group_lv"])
        sa.draw_dim_reduction_plot(pca, cluster_result=clust)
